/**
 * PostHog —— 从 open-connector 迁移的 provider(57 个 action:项目、事件/属性定义、
 * 标注、cohort、insight、query、dashboard、feature flag)。
 *
 * 分工同其他迁移产物:`schema.ts` 是生成的 Zod 声明,`api.ts` 是人工改写的业务逻辑,
 * 本文件把两张表对起来(键集合不吻合会在装配期炸)。
 *
 * `credentialProbe: 'get_current_user'` —— 三个条件都满足:已注册、`effect: 'read'`、
 * inputSchema 是 `z.strictObject({})` 没有必填字段。它打的正是上游 `credentialValidators`
 * 用的那个接口(`/api/users/@me/`),挂载时配错的 personal API key 当场被拒。
 *
 * 挂载还需要 `providerConfig.baseUrl`(US/EU/自托管三选一,见 api.ts 顶部)。它不是密钥,
 * 走 providerConfig 通道;探针调用也会带上它,所以 baseUrl 配错同样在挂载期暴露。
 */

